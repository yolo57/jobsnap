export function getT(lang) {
  const dict = translations[lang] || translations.en;
  const fallback = translations.en;
  return (key, ...args) => {
    const entry = dict[key] ?? fallback[key] ?? key;
    return typeof entry === 'function' ? entry(...args) : entry;
  };
}
